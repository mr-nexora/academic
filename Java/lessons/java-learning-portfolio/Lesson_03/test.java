package Lesson_03;

public class test9 {
    public static void main(String[] args) {

        // The Var Keyword
        var myNum = 5; // Integer (whole number)
        var myFloatNum = 5.99f; // Floating point number
        var myLetter = 'D'; // Character
        var myBool = true; // Boolean
        var myText = "Hello"; // String

        System.out.println("Int: " + myNum);
        System.out.println("Float: " + myFloatNum);
        System.out.println("Char: " + myLetter);
        System.out.println("Boolean: " + myBool);
        System.out.println("String: " + myText);

    }

}
