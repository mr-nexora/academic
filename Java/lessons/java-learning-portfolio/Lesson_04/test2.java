public class test2 { 
    public static void main(String [] args) {

    // Assignment Operators

    // = 
    int x = 5;
    System.out.println("x = " + x);
    
    // +=	
    x += 3;
    System.out.println("x = " + x);

    // -=	
    x -= 3;
    System.out.println("x = " + x);

    // *=	
    x *= 3;
    System.out.println("x = " + x);

    // /=	
    x /= 3;
    System.out.println("x = " + x);

    // %=	
    x %= 3;
    System.out.println("x = " + x);

    // &=	
    x &= 3;
    System.out.println("x = " + x);

    // |=	
    x |= 3;
    System.out.println("x = " + x);

    // ^=	
    x ^= 3;
    System.out.println("x = " + x);

    // >>=
    x >>= 3;
    System.out.println("x = " + x);

    // <<=
    x <<= 3;
    System.out.println("x = " + x);

     }
}
