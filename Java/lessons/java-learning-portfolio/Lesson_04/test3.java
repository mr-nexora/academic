
public class test3 {
    public static void main(String [] args) {

        //  Logical Operators

        int x = 10;

        // Logical And
        System.out.println("Logical And Output: " + (x >= 10 && x <20));

        // Logical Or
        System.out.println("Logical Or Output: " + (x>30 || x ==10));

        // Logical Not
        System.out.println("Logical Not Output: " + !(x>=10 && x<20));
    }
    
}
